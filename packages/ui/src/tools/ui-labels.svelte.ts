export type UiLabels = typeof defaultUiLabels;
export type UiLabelKey = keyof UiLabels;

export const uiLabels: UiLabels = $state({ ...defaultUiLabels });

/**
 * Overrides the shared UI chrome strings; keys left out keep their current value.
 */
export function setUiLabels(labels: Partial<UiLabels>) {
  Object.assign(uiLabels, labels);
}

/**
 * Replaces `{name}` tokens in a label with the matching values.
 */
export function formatUiLabel(label: string, values: Record<string, string | number>): string {
  return label.replace(/\{(\w+)\}/g, (token, name: string) => (name in values ? String(values[name]) : token));
}
